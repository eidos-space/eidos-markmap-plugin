import { build } from "esbuild"
import { mkdir, writeFile } from "node:fs/promises"

// markmap-view imports the whole d3 barrel. Prebundling removes unused d3-dsv,
// whose dynamic code generation is forbidden by the plugin source policy.
const result = await build({
  entryPoints: ["markmap-view"],
  bundle: true,
  write: false,
  minify: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  legalComments: "inline",
})
await mkdir("src/generated", { recursive: true })
await writeFile(
  "src/generated/markmap-view.js",
  `// @ts-nocheck\n// Generated by scripts/prepare-view.mjs; do not edit.\n${result.outputFiles[0].text}`
)
await writeFile(
  "src/generated/markmap-view.d.ts",
  'export { Markmap } from "markmap-view"\n'
)
